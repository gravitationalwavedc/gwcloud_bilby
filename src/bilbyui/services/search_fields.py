"""Curated field catalogue used by the search registry."""

from __future__ import annotations


def _field(
    surface: str,
    path: str,
    description: str,
    group: str,
    tier: int,
    *,
    advertised: str | None = None,
    visibility: str = "full",
    example: str | None = None,
    type_hint: str | None = None,
) -> dict[str, object]:
    """Build one uniform registry record."""

    return {
        "surface": surface,
        "path": path,
        "advertised": advertised or path,
        "description": description,
        "group": group,
        "tier": tier,
        "visibility": visibility,
        "example": example,
        "type_hint": type_hint,
    }


